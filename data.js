function paradigm(id, g) {
 const stem = id.slice(0, -({B1:2,C1:4}[g] ?? 1));
 return endings[g].split(' ').map((variants, i) =>
  variants.split('/').map(ending => (g === 'C1' && i === 3 ? unaccent(stem) : stem) + ending)
 );
}
const parseForms = value => value.split(' ').map(group => group.split('/'));
function glossaryCard(id, ru, page) {
 const topic = topics.get(id) ?? 'Повседневное';
 const source = book+', стр. '+page;
 if (observedThirdPerson.has(id)) {
  return {id, ru, topic, level:'A1+', source, g:'special', forms:[[],[],[id],[],[],[]],
   partial:true, formNote:'В учебнике приведена форма 3-го лица единственного числа в этом значении.'};
 }
 const table = tableForms[id];
 const extra = exceptional[id];
 const g = table?.[2] ?? extra?.[0] ?? (id.endsWith('άω') ? 'B1' : id.endsWith('ώ') ? 'B2' : id.endsWith('άμαι') ? 'C2' : id.endsWith('ομαι') ? 'C1' : 'A');
 const forms = table ? parseForms(table[1]) : extra ? parseForms(extra[1]) : paradigm(id,g);
 const stem = !extra && ['A','B1','B2'].includes(g) && id !== 'ζω' ? id.slice(0,g==='B1'?-2:-1) : '';
 return {id, ru, g, topic, level:g==='A' || g==='B1'?'A1':'A1+', source, forms, stem,
  formNote:table ? 'Таблица форм: '+book+', стр. '+table[0]+'.' : extra ?
   'Формы настоящего времени приведены справочно.' : 'Формы настоящего времени образованы по модели '+groups[g][0]+'.'};
}
